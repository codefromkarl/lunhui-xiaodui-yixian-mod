"""Seven-star original-card descriptions; no generated-output side effects."""
def describe_effects(card):
    r = card['rules']; lines = []
    original = ' '.join(card.get('originalText', '').split())
    lines.append('原牌依据：1级「' + card['name'] + '」（' + card.get('realm', '') + '）。原文：' + original)
    lines.append('本Mod换算：原攻／防／生命×3，灵气×4；单段能量100%、多段反应40%、盾能量70%、治疗体质50%、回气能量20%；特殊固定收益不再叠属性。')
    if r.get('starGain'): lines.append(f'获得{r["starGain"]}星力。星力常驻不消耗；位于星位时，每点星力使每次攻击额外+3攻，不加强非攻击伤害。')
    if r.get('omenGain'): lines.append(f'获得{r["omenGain"]}卦象。每次独立随机判定可耗1卦象取最优，不推进RNG；概率事件确保成功，重复随机逐次消耗。')
    if r.get('randomMax'):
        n=r.get('randomRepeats',1)
        lines.append(f'独立重复{n}次：随机攻击{r["randomMin"]*3}～{r["randomMax"]*3}，每次再加{"40%反应" if n>1 else "100%能量"}及适用星力；每次随机分别判定卦象。')
    if r.get('markNext'): lines.append(f'当前虚拟8格之后第{r["markNext"]}格永久成为星位；已是星位则恢复4斗气，不另叠属性。')
    for k,label,mul in [('positionAttack','另一次攻击',3),('positionDefense','护盾',3),('positionQi','斗气',4),('postAttack','另一次攻击',3),('postHeal','生命',3),('postGuard','护体',1)]:
        if r.get(k):
            mode='星位' if k.startswith('position') else '后招'
            suffix='，另加50%体质' if k=='postHeal' else ''
            extra='，另加100%能量' if k=='postAttack' and not r.get('damage') else ''
            lines.append(f'{mode}：获得{label}{r[k]*mul}{suffix}。' if label!='另一次攻击' else f'{mode}：追加一次{r[k]*mul}攻击{extra}（适用星位星力，不按基础多段数重复追加）。')
    if r.get('weakChance'): lines.append(f'{r["weakChance"]}%概率施加1层虚弱（攻击减少40%，1回合）；有卦象则本次概率必成并耗1点。')
    if r.get('flawChance'): lines.append(f'先判定{r["flawChance"]}%概率施加{r["flaw"]}层破绽，再攻击；破绽令攻击伤害增加40%，按原生回合计时；有卦象则本次概率必成。')
    if r.get('internal'): lines.append(f'施加{r["internal"]}层内伤；每层在目标行动阶段开始时直接减3生命。')
    if r.get('triggerInternal'): lines.append('新增内伤后，立即按目标现有内伤总层数直接减生命一次，每层3；不移除内伤。')
    if r.get('enemyQi'): lines.append(f'对方恢复{r["enemyQi"]*4}斗气（不超过其斗气上限，不叠属性）。')
    if r.get('shieldPerOmen'): lines.append(f'每点当前卦象额外获得{r["shieldPerOmen"]*3}护盾，不消费卦象。')
    if r.get('healPerOmen'): lines.append(f'每点当前卦象额外恢复{r["healPerOmen"]*3}生命，不消费卦象。')
    if r.get('refundOmen'): lines.append(f'返还本场经随机判定触发过的卦象数，最多{r["refundOmen"]}点；包含本牌刚触发的卦象，不包含星轨推衍的主动耗尽。')
    if r.get('hexFormation'): lines.append(f'持续：每实际增加1卦象，对当前敌目标造成{r["hexFormation"]*3}非攻击伤害；仍由护盾阻挡，忽略宿主护甲，不叠星力或攻击属性。')
    if r.get('enemyMaxHealth'): lines.append(f'对方生命上限减少{r["enemyMaxHealth"]*3}。')
    if r.get('enemyLoseHealth'): lines.append(f'对方直接减少{r["enemyLoseHealth"]*3}生命；上限降低已截掉的生命不重复扣除。')
    if r.get('consumeAllOmen'): lines.append('耗尽卦象，每点获得1星力、4斗气并恢复3生命；这不是随机触发，不计御雷卦诀返还数。')
    if r.get('qiOnOmen'): lines.append(f'本牌每次随机若由卦象确保上限，恢复{r["qiOnOmen"]*4}斗气；重复逐次结算。')
    if r.get('soulCharges'): lines.append(f'持续{r["soulCharges"]}次：每段攻击或受到攻击向该对手施加1内伤；非攻击伤害不触发。')
    if r.get('positionMaxHeal'): lines.append(f'星位：生命及上限+{r["positionMaxHeal"]*3}，每点当前星力再+{r["maxHealPerStar"]*3}；先增上限，再恢复生命。')
    if r.get('astralLinks'): lines.append(f'之后{r["astralLinks"]}次使用星弈牌：当前格已是星位则+1星力；否则当前格永久成为星位并恢复15生命。')
    if r.get('againChance'): lines.append(f'{r["againChance"]}%概率再次行动（适配额外摸1张）；卦象可确保本次概率成功。')
    if r.get('chanceRepeats'): lines.append(f'独立重复{r["chanceRepeats"]}次：{r["attackChance"]}%概率造成{r["chanceAttack"]*3}攻击，命中时另加40%反应及适用星力；每次概率单独使用卦象。')
    if r.get('againAtOmen'): lines.append(f'结算本牌卦象获得后，卦象≥{r["againAtOmen"]}则再次行动（额外摸1张）。')
    if r.get('again'): lines.append('再次行动：适配为额外摸1张，不自动打出、不额外获得行动力。')
    if r.get('postAgain'): lines.append('后招：再次行动（额外摸1张）。')
    if r.get('positionAgain'): lines.append('星位：再次行动（额外摸1张）。')
    if r.get('repeatNext'): lines.append('下一张七星阁牌连续结算两次，不二次支付、不重复推进牌序；原生牌不消费本门重施。第二次结算计入同名牌使用次数，因此可触发后招。')
    if r.get('positionSkip'): lines.append('星位：对方跳过下1张牌，适配为跳过目标下一次原生活动；控制受原生免疫规则约束。')
    if r.get('allPositions'): lines.append(f'持续：全部8格成为星位；若本牌在第1格，额外获得{r["firstSlotStar"]}星力。')
    if r.get('maxHealth'): lines.append(f'生命上限+{r["maxHealth"]*3}（不自动回血）。')
    if r.get('highestGain'): lines.append(f'在斗气÷4向下取整、卦象、星力中选最高者+{r["highestGain"]}；同值按斗气→卦象→星力；斗气增量×4。')
    if r.get('compareQiFlaw'): lines.append(f'本牌回气后，斗气高于对方则施加{r["compareQiFlaw"]}层破绽。')
    if r.get('positionAgainStars'): lines.append(f'星位且当前星力≥{r["positionAgainStars"]}：再次行动（额外摸1张）。')
    if r.get('defenseByNegative'): lines.append(f'获得护盾3，目标每层负面状态再+3，总计最多{r["defenseCap"]*3}；当前总护盾≥{r["againAtDefense"]*3}则额外摸1张。')
    if r.get('injuryRounds'): lines.append(f'持续{r["injuryRounds"]}个原生大回合：本门攻击每段施加1内伤（本牌也生效）。')
    if r.get('bonusChance'): lines.append(f'{r["bonusChance"]}%概率追加{r["bonusAttack"]*3}攻击×{r["bonusHits"]}段（每段适用星力）；独立卦象判定。')
    if r.get('decreaseChance'): lines.append(f'{r["decreaseChance"]}%概率施加1减攻（每层攻击-3）；独立卦象判定。')
    if r.get('oddStar'): lines.append(f'奇数格：获得{r["oddStar"]}星力。')
    if r.get('evenStarGuard'): lines.append(f'偶数格：将最多{r["evenStarGuard"]}星力转为相同层护体，每层抵挡1次伤害；最多32个独立实例，达到上限不再增加，星力仍按转化数量消耗。')
    if r.get('postGuard'): lines.append('护体每层抵挡1次伤害；最多32个独立实例，达到上限不再增加。')
    if r.get('negativeOmen'): lines.append(f'本牌施加新负面状态前，若对方已有负面状态，额外获得{r["negativeOmen"]}卦象。')
    if r.get('oddInternal'): lines.append(f'奇数格：施加{r["oddInternal"]}内伤。')
    if r.get('evenExternal'): lines.append(f'偶数格：施加{r["evenExternal"]}外伤（目标每次受到攻击多3伤害）。')
    if r.get('persistent'): lines.append('持续牌本场只生效一次；再次手动使用同牌不重复叠加持续效果。')
    lines.append('星位：本场成功卡牌循环映射1～8格，默认3／6格；外部卡牌也推进，抽牌／移动／普攻不计。后招：本场同名原牌第2次及以后；大回合切换不清除牌序、星位、星力和卦象。')
    lines.extend('适配：' + a for a in card.get('adaptation', [])[1:])
    lines.extend('来源差异：' + a for a in card.get('sourceDiscrepancies', []))
    return lines
